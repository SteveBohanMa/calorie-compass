function clock(time: string, lang: Lang) {
  return new Date(time).toLocaleTimeString(lang === "zh" ? "zh-CN" : "en-US", { hour: "2-digit", minute: "2-digit", hour12: false });
}

function day(time: string, lang: Lang) {
  return new Date(time).toLocaleDateString(lang === "zh" ? "zh-CN" : "en-US", { month: "short", day: "numeric" });
}

